// Folder and settings contours follow DeepSeek Harness's MIT-licensed icon artwork.
export function icon(spec: PluginIcon = 'plugin') {
  const name = typeof spec === 'string' ? spec : '';
  const custom = typeof spec === 'object' && spec !== null ? spec : undefined;
  const iconPath =
    custom?.path ?? (Object.hasOwn(paths, name) ? paths[name as keyof typeof paths] : paths.plugin);
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  const dsh =
    name === 'settings' ||
    name === 'folder' ||
    name === 'folder-open' ||
    name === 'ellipsis' ||
    name === 'new-chat' ||
    name === 'triangle';
  svg.setAttribute(
    'viewBox',
    custom?.viewBox ?? (name === 'settings' ? '.5 .5 15 15' : dsh ? '0 0 16 16' : '0 0 24 24'),
  );
  svg.setAttribute('width', '18');
  svg.setAttribute('height', '18');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', dsh ? (name === 'settings' ? '1.3' : '1') : '1.7');
  svg.setAttribute('stroke-linecap', dsh ? 'butt' : 'round');
  svg.setAttribute('stroke-linejoin', dsh ? 'miter' : 'round');
  svg.setAttribute('aria-hidden', 'true');
  const path = document.createElementNS(svg.namespaceURI, 'path');
  path.setAttribute('d', iconPath);
  if (dsh) path.setAttribute('vector-effect', 'non-scaling-stroke');
  if (name === 'ellipsis' || name === 'triangle') {
    path.setAttribute('fill', 'currentColor');
    path.setAttribute('stroke', 'none');
  }
  svg.append(path);
  return svg;
}
export function hydrateIcons(root: ParentNode = document) {
  const nodes = [...root.querySelectorAll<HTMLElement>('[data-icon]')];
  if (root instanceof HTMLElement && root.matches('[data-icon]')) nodes.unshift(root);
  for (const node of nodes) {
    node.replaceChildren(icon(node.dataset.icon ?? 'plugin'));
    node.removeAttribute('data-icon');
  }
}

export function fileLabel(node: HTMLElement, name: string, kind: 'file' | 'folder' | 'folder-open') {
  const label = document.createElement('span');
  label.textContent = name;
  node.append(icon(kind), label);
}
